-- #############################################################################
-- PHASE 2: STAGING — Type-cast, normalize, validate
-- #############################################################################
-- Every STAGING table:
--   - Casts VARCHAR dates to DATE, numeric strings to NUMBER/FLOAT
--   - Adds _VALID BOOLEAN: FALSE if arrival_date < departure_date
--   - Preserves ALL source rows (invalid rows kept with _VALID=FALSE)
-- #############################################################################

USE SCHEMA STAGING;

-- STG_SHIPMENT: cast dates and quantities, validate arrival >= departure
CREATE OR REPLACE TABLE STG_SHIPMENT AS
SELECT
    SHIPMENT_ID,
    SHIPMENT_NAME,
    ORIGIN_LOCATION_ID,
    ORIGIN_LOCATION_NAME,
    DESTINATION_LOCATION_ID,
    DESTINATION_LOCATION_NAME,
    TRY_TO_DATE(DEPARTING_ORIGIN_DATE)     AS DEPARTURE_DATE,
    TRY_TO_DATE(ARRIVING_DESTINATION_DATE) AS ARRIVAL_DATE,
    ORIGIN_LOCATION_GEOHASH,
    DESTINATION_LOCATION_GEOHASH,
    VEHICLE_ID,
    VEHICLE_NAME,
    TRY_TO_NUMBER(VEHICLE_UNIT_CAPACITY)   AS VEHICLE_CAPACITY,
    TRY_TO_NUMBER(TOTAL_UNIT_QUANTITY)     AS TOTAL_UNIT_QUANTITY,
    STATUS,
    -- Validation: arrival must be on or after departure
    CASE
        WHEN TRY_TO_DATE(ARRIVING_DESTINATION_DATE) >= TRY_TO_DATE(DEPARTING_ORIGIN_DATE)
        THEN TRUE ELSE FALSE
    END AS _VALID,
    LOAD_TIMESTAMP,
    SOURCE_FILE
FROM RAW.RAW_SHIPMENT;

-- STG_PRODUCT_SHIPMENT: cast quantity and dates, validate
CREATE OR REPLACE TABLE STG_PRODUCT_SHIPMENT AS
SELECT
    PRODUCT_SHIPMENT_ID,
    SHIPMENT_ID,
    SHIPMENT_NAME,
    PRODUCT_ID,
    PRODUCT_DESCRIPTION,
    TRY_TO_NUMBER(QUANTITY)                AS QUANTITY,
    TRY_TO_DATE(DEPARTING_ORIGIN_DATE)     AS DEPARTURE_DATE,
    TRY_TO_DATE(ARRIVING_DESTINATION_DATE) AS ARRIVAL_DATE,
    VEHICLE_NAME,
    ORIGIN_LOCATION_NAME,
    ORIGIN_LOCATION_GEOHASH,
    DESTINATION_LOCATION_NAME,
    DESTINATION_LOCATION_GEOHASH,
    PRODUCT_SHIPMENT_NAME,
    CASE
        WHEN TRY_TO_DATE(ARRIVING_DESTINATION_DATE) >= TRY_TO_DATE(DEPARTING_ORIGIN_DATE)
        THEN TRUE ELSE FALSE
    END AS _VALID,
    LOAD_TIMESTAMP,
    SOURCE_FILE
FROM RAW.RAW_PRODUCT_SHIPMENT;

-- STG_PRODUCT: pass-through (no casting needed, already VARCHAR)
CREATE OR REPLACE TABLE STG_PRODUCT AS
SELECT PRODUCT_ID, PRODUCT_DESCRIPTION, TRUE AS _VALID, LOAD_TIMESTAMP, SOURCE_FILE
FROM RAW.RAW_PRODUCT;

-- STG_LOCATION: parse lat/lon from geohash string
CREATE OR REPLACE TABLE STG_LOCATION AS
SELECT
    LOCATION_ID,
    NAME AS LOCATION_NAME,
    GEOHASH,
    TRY_TO_DOUBLE(SPLIT_PART(GEOHASH, ',', 1)) AS LATITUDE,
    TRY_TO_DOUBLE(SPLIT_PART(GEOHASH, ',', 2)) AS LONGITUDE,
    TRUE AS _VALID,
    LOAD_TIMESTAMP,
    SOURCE_FILE
FROM RAW.RAW_LOCATION;

-- STG_VEHICLE: cast capacity to number
CREATE OR REPLACE TABLE STG_VEHICLE AS
SELECT
    VEHICLE_ID, VEHICLE_NAME,
    TRY_TO_NUMBER(UNIT_CAPACITY) AS UNIT_CAPACITY,
    TRUE AS _VALID, LOAD_TIMESTAMP, SOURCE_FILE
FROM RAW.RAW_VEHICLE;

-- STG_SUPPLIER: cast numeric fields
CREATE OR REPLACE TABLE STG_SUPPLIER AS
SELECT
    SUPPLIER_ID, SUPPLIER_NAME, PRODUCT_ID, PARTS_SUPPLIED, REGION, TIER,
    TRY_TO_DOUBLE(RELIABILITY_SCORE) AS RELIABILITY_SCORE,
    TRY_TO_NUMBER(LEAD_TIME_DAYS)    AS LEAD_TIME_DAYS,
    TRUE AS _VALID, LOAD_TIMESTAMP, SOURCE_FILE
FROM RAW.RAW_SUPPLIER;

-- STG_CUSTOMER: pass-through
CREATE OR REPLACE TABLE STG_CUSTOMER AS
SELECT
    CUSTOMER_ID, CUSTOMER_NAME, LOCATION_ID, LOCATION_NAME, REGION, SEGMENT,
    TRUE AS _VALID, LOAD_TIMESTAMP, SOURCE_FILE
FROM RAW.RAW_CUSTOMER;

-- STG_ORDER: cast dates and quantities
CREATE OR REPLACE TABLE STG_ORDER AS
SELECT
    ORDER_ID, SHIPMENT_ID, CUSTOMER_ID, DESTINATION_LOCATION_ID,
    TRY_TO_DATE(ORDER_DATE)               AS ORDER_DATE,
    TRY_TO_DATE(REQUESTED_DELIVERY_DATE)  AS REQUESTED_DELIVERY_DATE,
    TRY_TO_DATE(ACTUAL_DELIVERY_DATE)     AS ACTUAL_DELIVERY_DATE,
    TRY_TO_NUMBER(ORDERED_QUANTITY)       AS ORDERED_QUANTITY,
    TRY_TO_NUMBER(SHIPPED_QUANTITY)       AS SHIPPED_QUANTITY,
    PRIORITY, STATUS,
    CASE WHEN TRY_TO_DATE(ORDER_DATE) IS NOT NULL THEN TRUE ELSE FALSE END AS _VALID,
    LOAD_TIMESTAMP, SOURCE_FILE
FROM RAW.RAW_ORDER;

-- STG_COST: cast all numeric fields
CREATE OR REPLACE TABLE STG_COST AS
SELECT
    PRODUCT_SHIPMENT_ID, PRODUCT_ID,
    TRY_TO_NUMBER(QUANTITY)       AS QUANTITY,
    TRY_TO_DOUBLE(UNIT_COST)     AS UNIT_COST,
    TRY_TO_DOUBLE(MATERIAL_COST) AS MATERIAL_COST,
    TRY_TO_DOUBLE(FREIGHT_COST)  AS FREIGHT_COST,
    TRY_TO_DOUBLE(DUTY_RATE)     AS DUTY_RATE,
    TRY_TO_DOUBLE(DUTY_COST)     AS DUTY_COST,
    TRY_TO_DOUBLE(HANDLING_COST) AS HANDLING_COST,
    TRY_TO_DOUBLE(LANDED_COST)   AS LANDED_COST,
    TRY_TO_DOUBLE(DISTANCE_KM)   AS DISTANCE_KM,
    TRUE AS _VALID, LOAD_TIMESTAMP, SOURCE_FILE
FROM RAW.RAW_COST;

-- STG_INVENTORY: cast date and quantities
CREATE OR REPLACE TABLE STG_INVENTORY AS
SELECT
    LOCATION_ID, PRODUCT_ID,
    TRY_TO_DATE(SNAPSHOT_DATE)         AS SNAPSHOT_DATE,
    TRY_TO_NUMBER(INVENTORY_QUANTITY)  AS INVENTORY_QUANTITY,
    TRY_TO_NUMBER(DAILY_DEMAND)        AS DAILY_DEMAND,
    TRY_TO_NUMBER(INBOUND_QUANTITY)    AS INBOUND_QUANTITY,
    TRUE AS _VALID, LOAD_TIMESTAMP, SOURCE_FILE
FROM RAW.RAW_INVENTORY;


-- #############################################################################
-- PHASE 3: LOAD CORE DIMENSIONS
-- #############################################################################
-- INSERT OVERWRITE = idempotent (full refresh each run).
-- Only _VALID=TRUE rows from STAGING flow into CORE.
-- #############################################################################

USE SCHEMA CORE;

-- DIM_PLANT: from STG_LOCATION (4 rows)
-- Lat/lon parsed in staging from the "lat,lon" geohash string.
INSERT OVERWRITE INTO SUPPLYCHAIN_DB.CORE.DIM_PLANT
    (PLANT_ID, PLANT_NAME, REGION, LATITUDE, LONGITUDE)
SELECT LOCATION_ID, LOCATION_NAME, 'AMERICAS', LATITUDE, LONGITUDE
FROM SUPPLYCHAIN_DB.STAGING.STG_LOCATION
WHERE _VALID = TRUE;

-- DIM_SUPPLIER: from STG_SUPPLIER (6 rows)
INSERT OVERWRITE INTO SUPPLYCHAIN_DB.CORE.DIM_SUPPLIER
    (SUPPLIER_ID, SUPPLIER_NAME, REGION, TIER, RELIABILITY_SCORE, LEAD_TIME_DAYS)
SELECT SUPPLIER_ID, SUPPLIER_NAME, REGION, TIER, RELIABILITY_SCORE, LEAD_TIME_DAYS
FROM SUPPLYCHAIN_DB.STAGING.STG_SUPPLIER
WHERE _VALID = TRUE;

-- DIM_PART: join STG_PRODUCT + STG_COST (unit_cost) + STG_SUPPLIER (primary supplier)
-- Category inferred from second word of product_description (Triangles/Squares/Circles).
-- Primary supplier = Tier 1 for that product.
INSERT OVERWRITE INTO SUPPLYCHAIN_DB.CORE.DIM_PART
    (PART_ID, PART_NAME, CATEGORY, UNIT_COST, SUPPLIER_ID)
SELECT
    p.PRODUCT_ID,
    p.PRODUCT_DESCRIPTION,
    SPLIT_PART(p.PRODUCT_DESCRIPTION, ' ', 2) AS CATEGORY,
    c.UNIT_COST,
    s.SUPPLIER_ID
FROM SUPPLYCHAIN_DB.STAGING.STG_PRODUCT p
JOIN (SELECT DISTINCT PRODUCT_ID, UNIT_COST FROM SUPPLYCHAIN_DB.STAGING.STG_COST) c
    ON p.PRODUCT_ID = c.PRODUCT_ID
JOIN SUPPLYCHAIN_DB.STAGING.STG_SUPPLIER s
    ON p.PRODUCT_ID = s.PRODUCT_ID AND s.TIER = 'Tier 1';

-- DIM_CUSTOMER: from STG_CUSTOMER (8 rows)
-- LOCATION_ID maps to PLANT_ID (same values, different domain name).
INSERT OVERWRITE INTO SUPPLYCHAIN_DB.CORE.DIM_CUSTOMER
    (CUSTOMER_ID, CUSTOMER_NAME, REGION, SEGMENT, PLANT_ID)
SELECT CUSTOMER_ID, CUSTOMER_NAME, REGION, SEGMENT, LOCATION_ID
FROM SUPPLYCHAIN_DB.STAGING.STG_CUSTOMER
WHERE _VALID = TRUE;


-- #############################################################################
-- PHASE 4: LOAD CORE FACTS
-- #############################################################################

-- FACT_ORDER: from STG_ORDER (83 rows)
-- PART_ID = the product with highest quantity in the linked shipment
-- (one shipment can carry 1–3 products; we pick the dominant one).
INSERT OVERWRITE INTO SUPPLYCHAIN_DB.CORE.FACT_ORDER
    (ORDER_ID, CUSTOMER_ID, PLANT_ID, PART_ID, ORDER_DATE,
     REQUESTED_DELIVERY_DATE, ORDERED_QUANTITY, PRIORITY, STATUS)
SELECT
    o.ORDER_ID,
    o.CUSTOMER_ID,
    o.DESTINATION_LOCATION_ID AS PLANT_ID,
    ps.PRODUCT_ID             AS PART_ID,
    o.ORDER_DATE,
    o.REQUESTED_DELIVERY_DATE,
    o.ORDERED_QUANTITY,
    o.PRIORITY,
    o.STATUS
FROM SUPPLYCHAIN_DB.STAGING.STG_ORDER o
JOIN (
    -- Pick dominant product per shipment (highest quantity)
    SELECT SHIPMENT_ID, PRODUCT_ID,
           ROW_NUMBER() OVER (PARTITION BY SHIPMENT_ID ORDER BY QUANTITY DESC) AS RN
    FROM SUPPLYCHAIN_DB.STAGING.STG_PRODUCT_SHIPMENT
    WHERE _VALID = TRUE
) ps ON o.SHIPMENT_ID = ps.SHIPMENT_ID AND ps.RN = 1
WHERE o._VALID = TRUE;


-- FACT_INVENTORY: from STG_INVENTORY (360 rows)
INSERT OVERWRITE INTO SUPPLYCHAIN_DB.CORE.FACT_INVENTORY
    (PLANT_ID, PART_ID, SNAPSHOT_DATE, INVENTORY_QUANTITY, DAILY_DEMAND, INBOUND_QUANTITY)
SELECT LOCATION_ID, PRODUCT_ID, SNAPSHOT_DATE, INVENTORY_QUANTITY, DAILY_DEMAND, INBOUND_QUANTITY
FROM SUPPLYCHAIN_DB.STAGING.STG_INVENTORY
WHERE _VALID = TRUE;


-- FACT_SHIPMENT: the most complex load — 4-way join + PySpark-derived columns
-- Grain: 1 row per shipment × part (159 rows from product_shipment).
--
-- Join chain:
--   STG_PRODUCT_SHIPMENT  (grain: 159 rows, the product line items)
--   + STG_SHIPMENT         (route, vehicle, dates — joined on shipment_id)
--   + STG_ORDER            (order linkage + requested_delivery_date — joined on shipment_id)
--   + STG_COST             (cost measures — joined on product_shipment_id)
--
-- PySpark transformation logic (from src/transformation.py) preserved exactly:
--   Step 1: delivery_days = DATEDIFF('day', departure_date, arrival_date)
--   Step 2: is_valid_shipment = delivery_days >= 0
--   Step 3: avg_route_delivery_days = AVG(delivery_days) OVER (PARTITION BY origin, dest)
--   Step 4: risk_flag = High if > avg+3, Medium if > avg, else Low
--   Step 5: decision = Investigate / Monitor / Normal

INSERT OVERWRITE INTO SUPPLYCHAIN_DB.CORE.FACT_SHIPMENT (
    SHIPMENT_LINE_ID, SHIPMENT_ID, ORDER_ID, PART_ID,
    ORIGIN_PLANT_ID, DESTINATION_PLANT_ID, VEHICLE_ID,
    DEPARTURE_DATE, ARRIVAL_DATE, REQUESTED_DELIVERY_DATE,
    SHIPPED_QUANTITY, VEHICLE_CAPACITY,
    UNIT_COST, MATERIAL_COST, FREIGHT_COST, DUTY_COST,
    HANDLING_COST, LANDED_COST, DISTANCE_KM,
    DELIVERY_DAYS, IS_VALID_SHIPMENT, AVG_ROUTE_DELIVERY_DAYS,
    RISK_FLAG, DECISION
)
WITH shipment_base AS (
    -- CTE 1: Join product_shipment lines with parent shipment for route info
    SELECT
        ps.PRODUCT_SHIPMENT_ID    AS SHIPMENT_LINE_ID,
        ps.SHIPMENT_ID,
        ps.PRODUCT_ID             AS PART_ID,
        s.ORIGIN_LOCATION_ID      AS ORIGIN_PLANT_ID,
        s.DESTINATION_LOCATION_ID AS DESTINATION_PLANT_ID,
        s.VEHICLE_ID,
        s.DEPARTURE_DATE,
        s.ARRIVAL_DATE,
        s.VEHICLE_CAPACITY,
        ps.QUANTITY               AS SHIPPED_QUANTITY,
        s.ORIGIN_LOCATION_NAME,
        s.DESTINATION_LOCATION_NAME
    FROM SUPPLYCHAIN_DB.STAGING.STG_PRODUCT_SHIPMENT ps
    JOIN SUPPLYCHAIN_DB.STAGING.STG_SHIPMENT s
        ON ps.SHIPMENT_ID = s.SHIPMENT_ID
    WHERE ps._VALID = TRUE AND s._VALID = TRUE
),
with_order AS (
    -- CTE 2: Attach order_id and requested_delivery_date via shipment_id
    SELECT
        sb.*,
        o.ORDER_ID,
        o.REQUESTED_DELIVERY_DATE
    FROM shipment_base sb
    JOIN SUPPLYCHAIN_DB.STAGING.STG_ORDER o
        ON sb.SHIPMENT_ID = o.SHIPMENT_ID
),
with_costs AS (
    -- CTE 3: Attach cost measures + compute delivery_days and is_valid
    SELECT
        wo.*,
        c.UNIT_COST,
        c.MATERIAL_COST,
        c.FREIGHT_COST,
        c.DUTY_COST,
        c.HANDLING_COST,
        c.LANDED_COST,
        c.DISTANCE_KM,
        -- PySpark Step 1: delivery_days
        DATEDIFF('day', wo.DEPARTURE_DATE, wo.ARRIVAL_DATE)        AS DELIVERY_DAYS,
        -- PySpark Step 2: is_valid_shipment
        DATEDIFF('day', wo.DEPARTURE_DATE, wo.ARRIVAL_DATE) >= 0   AS IS_VALID_SHIPMENT
    FROM with_order wo
    JOIN SUPPLYCHAIN_DB.STAGING.STG_COST c
        ON wo.SHIPMENT_LINE_ID = c.PRODUCT_SHIPMENT_ID
),
with_route_avg AS (
    -- CTE 4: PySpark Step 3 — route-level average delivery days
    -- Window partition matches PySpark exactly: (origin_location_name, destination_location_name)
    SELECT
        wc.*,
        AVG(DELIVERY_DAYS) OVER (
            PARTITION BY ORIGIN_LOCATION_NAME, DESTINATION_LOCATION_NAME
        ) AS AVG_ROUTE_DELIVERY_DAYS
    FROM with_costs wc
)
-- Final SELECT: PySpark Steps 4+5 — risk_flag and decision
SELECT
    SHIPMENT_LINE_ID, SHIPMENT_ID, ORDER_ID, PART_ID,
    ORIGIN_PLANT_ID, DESTINATION_PLANT_ID, VEHICLE_ID,
    DEPARTURE_DATE, ARRIVAL_DATE, REQUESTED_DELIVERY_DATE,
    SHIPPED_QUANTITY, VEHICLE_CAPACITY,
    UNIT_COST, MATERIAL_COST, FREIGHT_COST, DUTY_COST, HANDLING_COST, LANDED_COST, DISTANCE_KM,
    DELIVERY_DAYS,
    IS_VALID_SHIPMENT,
    AVG_ROUTE_DELIVERY_DAYS,
    -- PySpark Step 4: risk_flag (evaluated top-down, same order as CASE WHEN)
    CASE
        WHEN DELIVERY_DAYS > AVG_ROUTE_DELIVERY_DAYS + 3 THEN 'High'
        WHEN DELIVERY_DAYS > AVG_ROUTE_DELIVERY_DAYS     THEN 'Medium'
        ELSE 'Low'
    END AS RISK_FLAG,
    -- PySpark Step 5: decision mapping
    CASE
        WHEN DELIVERY_DAYS > AVG_ROUTE_DELIVERY_DAYS + 3 THEN 'Investigate'
        WHEN DELIVERY_DAYS > AVG_ROUTE_DELIVERY_DAYS     THEN 'Monitor'
        ELSE 'Normal'
    END AS DECISION
FROM with_route_avg;


