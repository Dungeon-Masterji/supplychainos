-- =============================================================================
-- SupplyChainOS: End-to-End ETL Pipeline
-- =============================================================================
-- RAW → STAGING → CORE (full load, idempotent, re-runnable)
--
-- Prerequisites:
--   1. Run 01_setup_database.sql   (database, schemas, file format, stage)
--   2. Run 02_create_raw_tables.sql (5 source RAW tables)
--   3. Run 03_create_core_tables.sql (7 CORE tables)
--   4. PUT all 10 CSV files to @SUPPLY_CHAIN_STAGE (source/ and synthetic/)
--
-- This script:
--   Phase 1: COPY INTO RAW tables from staged CSVs
--   Phase 2: Create STAGING tables (type-cast, validated)
--   Phase 3: INSERT OVERWRITE into CORE dimensions
--   Phase 4: INSERT OVERWRITE into CORE facts (incl. PySpark logic)
--   Phase 5: Validate every CORE table
--   Phase 6: Reconciliation report + sample rows
-- =============================================================================

USE DATABASE SUPPLYCHAIN_DB;
USE SCHEMA RAW;


-- #############################################################################
-- PHASE 1: LOAD RAW — COPY INTO from staged CSVs
-- #############################################################################
-- Each COPY uses ON_ERROR='ABORT_STATEMENT' so any parse failure stops the load.
-- FORCE=TRUE allows re-running without needing to re-PUT files.
-- SOURCE_FILE is populated from METADATA$FILENAME for audit lineage.
-- #############################################################################

-- ─── 1a. Create RAW tables for synthetic CSVs (source RAW tables already exist) ─

CREATE TABLE IF NOT EXISTS RAW_SUPPLIER (
    SUPPLIER_ID VARCHAR NOT NULL, SUPPLIER_NAME VARCHAR NOT NULL,
    PRODUCT_ID VARCHAR NOT NULL, PARTS_SUPPLIED VARCHAR NOT NULL,
    REGION VARCHAR NOT NULL, TIER VARCHAR NOT NULL,
    RELIABILITY_SCORE VARCHAR NOT NULL, LEAD_TIME_DAYS VARCHAR NOT NULL,
    LOAD_TIMESTAMP TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    SOURCE_FILE VARCHAR,
    CONSTRAINT PK_RAW_SUPPLIER PRIMARY KEY (SUPPLIER_ID)
);

CREATE TABLE IF NOT EXISTS RAW_CUSTOMER (
    CUSTOMER_ID VARCHAR NOT NULL, CUSTOMER_NAME VARCHAR NOT NULL,
    LOCATION_ID VARCHAR NOT NULL, LOCATION_NAME VARCHAR NOT NULL,
    REGION VARCHAR NOT NULL, SEGMENT VARCHAR NOT NULL,
    LOAD_TIMESTAMP TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    SOURCE_FILE VARCHAR,
    CONSTRAINT PK_RAW_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS RAW_ORDER (
    ORDER_ID VARCHAR NOT NULL, SHIPMENT_ID VARCHAR NOT NULL,
    CUSTOMER_ID VARCHAR NOT NULL, DESTINATION_LOCATION_ID VARCHAR NOT NULL,
    ORDER_DATE VARCHAR NOT NULL, REQUESTED_DELIVERY_DATE VARCHAR NOT NULL,
    ACTUAL_DELIVERY_DATE VARCHAR NOT NULL, ORDERED_QUANTITY VARCHAR NOT NULL,
    SHIPPED_QUANTITY VARCHAR NOT NULL, PRIORITY VARCHAR NOT NULL,
    STATUS VARCHAR NOT NULL,
    LOAD_TIMESTAMP TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    SOURCE_FILE VARCHAR,
    CONSTRAINT PK_RAW_ORDER PRIMARY KEY (ORDER_ID)
);

CREATE TABLE IF NOT EXISTS RAW_COST (
    PRODUCT_SHIPMENT_ID VARCHAR NOT NULL, PRODUCT_ID VARCHAR NOT NULL,
    QUANTITY VARCHAR NOT NULL, UNIT_COST VARCHAR NOT NULL,
    MATERIAL_COST VARCHAR NOT NULL, FREIGHT_COST VARCHAR NOT NULL,
    DUTY_RATE VARCHAR NOT NULL, DUTY_COST VARCHAR NOT NULL,
    HANDLING_COST VARCHAR NOT NULL, LANDED_COST VARCHAR NOT NULL,
    DISTANCE_KM VARCHAR NOT NULL,
    LOAD_TIMESTAMP TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    SOURCE_FILE VARCHAR,
    CONSTRAINT PK_RAW_COST PRIMARY KEY (PRODUCT_SHIPMENT_ID)
);

CREATE TABLE IF NOT EXISTS RAW_INVENTORY (
    LOCATION_ID VARCHAR NOT NULL, PRODUCT_ID VARCHAR NOT NULL,
    SNAPSHOT_DATE VARCHAR NOT NULL, INVENTORY_QUANTITY VARCHAR NOT NULL,
    DAILY_DEMAND VARCHAR NOT NULL, INBOUND_QUANTITY VARCHAR NOT NULL,
    LOAD_TIMESTAMP TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    SOURCE_FILE VARCHAR,
    CONSTRAINT PK_RAW_INVENTORY PRIMARY KEY (LOCATION_ID, PRODUCT_ID, SNAPSHOT_DATE)
);


